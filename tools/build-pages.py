def build(source, output):
    source, output = Path(source).resolve(), Path(output).resolve()
    if output == source or source.is_relative_to(output):
        raise ValueError('The output directory must not contain the source repository.')
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise ValueError('Choose a new or empty output directory; existing files are never removed.')
    files = [source / name for name in STATIC]
    for name, folders in GAMES.items():
        game = source / 'jogar' / name
        files += [game / 'index.html']
        for folder, extensions in folders:
            files += [p for p in ((game / folder).glob('*') if folder == '.' else (game / folder).rglob('*'))
                      if p.is_file() and p.suffix in extensions]
    for folder, extensions in FOLDERS.items():
        files += sorted(p for p in (source / folder).rglob('*') if p.is_file() and p.suffix in extensions)
    for p in files:
        if not p.is_file() or not p.resolve().is_relative_to(source) or p.is_symlink():
            raise ValueError(f'Missing or unsafe public asset: {p}')
        if p.stat().st_size > 25 * 1024 * 1024:
            raise ValueError(f'Public asset exceeds the Pages size limit: {p}')
    for p in files:
        dest = output / p.relative_to(source)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, dest)
    # English, Spanish and French copies of every page (<out>/en/, es/, fr/) plus their hreflang links.
    translated = i18n_pages.build(source, output) if (source / 'i18n').is_dir() else []
    for dest in [output / p.relative_to(source) for p in files if p.suffix == '.html'] + translated:
        dest.write_text(version_assets(dest.read_text(encoding='utf-8'), dest.parent, output), encoding='utf-8')
    return len(files) + len(translated)


ASSET_REF = re.compile(r'((?:href|src)=")([^"?#:]+\.(?:css|js))(?:\?[^"#]*)?(")')


def version_assets(html, folder, output):
    """Point every local .css/.js reference at ?v=<content hash>, so a returning visitor never
    pairs new HTML with a stylesheet or script cached from an older deploy."""
    def repl(m):
        path = m.group(2)
        if path.startswith('//'):
            return m.group(0)
        target = (output / path.lstrip('/')) if path.startswith('/') else (folder / path)
        if not target.is_file():
            return m.group(0)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:10]
        return f'{m.group(1)}{path}?v={digest}{m.group(3)}'
    return ASSET_REF.sub(repl, html)


